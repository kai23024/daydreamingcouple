export interface Category {
  slug: string
  name: string
  nameEn: string
  description: string
}

export interface ArticleImageBlock {
  images: string[]
}

export interface ArticleCaptionBlock {
  caption: string
}

export interface ArticleHeadingBlock {
  heading: string
  /** 1 = 大標 (major section heading), 2 = 小標 (sub-heading). Defaults to 1. */
  level?: 1 | 2
}

export interface ArticleListItem {
  text: string
  /** Nested second-level bullets under this item (e.g. transport modes under "交通與停車方式："). */
  sub?: string[]
}

export interface ArticleListBlock {
  /** A bullet list, optionally two-level, matching docx paragraphs with a bullet/hanging-indent list style. */
  items: (string | ArticleListItem)[]
  /** Use numbered (1/2/3) markers instead of bullets — for lists whose order is meaningful, e.g. numbers that match labels on an accompanying map image. */
  ordered?: boolean
}

export interface ArticleInfoBoxBlock {
  /** A highlighted quick-facts box (address, hours, price, etc.) rendered as a shaded bullet list — matches a docx "旅遊懶人包"-style callout box. */
  infoBox: string[]
}

