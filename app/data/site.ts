export function articlesByCategory(slug: string): Article[] {
  return articles.filter(a => a.category === slug)
}

export function categoryBySlug(slug: string): Category | undefined {
  return categories.find(c => c.slug === slug)
}

export function articleById(category: string, id: string): Article | undefined {
  return articles.find(a => a.category === category && a.id === id)
}

/** First prose paragraph of the article body, used as the card/preview excerpt. */
export function articleExcerpt(article: Article): string {
  const first = article.body.find((block): block is string => typeof block === 'string')
  return first ?? ''
}
